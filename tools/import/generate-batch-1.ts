function makeQuestion(seed: QuestionSeed, index: number): Question {
  return {
    id: `${seed.subject}-generated-batch-1-${String(index).padStart(3, "0")}`,
    subject: seed.subject,
    type: seed.passage ? "passage_single_choice" : "single_choice",
    topic: seed.topic,
    subtopic: seed.subtopic,
    difficulty: seed.difficulty,
    sourceType: "generated",
    sourceUrl: null,
    reviewed: false,
    question: seed.question,
    passage: seed.passage,
    options: seed.options,
    correctAnswer: seed.correctAnswer,
    explanation: seed.explanation,
    tags: seed.tags
  };
}

