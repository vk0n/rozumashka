function assertUniqueSingleAnswer(questions: Question[]): void {
  const ids = new Set<string>();

  for (const question of questions) {
    if (ids.has(question.id)) {
      throw new Error(`Duplicate id ${question.id}`);
    }
    ids.add(question.id);

    if (question.options.length !== 4) {
      throw new Error(`${question.id} must have exactly 4 options`);
    }

    if (new Set(question.options.map((option) => option.trim().toLowerCase())).size !== question.options.length) {
      throw new Error(`${question.id} has duplicate options`);
    }

    if (question.correctAnswer < 0 || question.correctAnswer >= question.options.length) {
      throw new Error(`${question.id} has invalid correctAnswer`);
    }

    if (question.type === "passage_single_choice" && !question.passage) {
      throw new Error(`${question.id} is passage_single_choice without passage`);
    }
  }
}

function distributionBy<T extends string>(questions: Question[], selector: (question: Question) => T): Record<T, number> {
  return questions.reduce<Record<T, number>>((accumulator, question) => {
    const key = selector(question);
    accumulator[key] = (accumulator[key] ?? 0) + 1;
    return accumulator;
  }, {} as Record<T, number>);
}

function markdownDistribution(title: string, distribution: Record<string, number>): string {
  const lines = Object.entries(distribution)
    .sort(([left], [right]) => left.localeCompare(right, "uk"))
    .map(([key, count]) => `- ${key}: ${count}`);

  return `## ${title}\n\n${lines.join("\n")}`;
}

async function writeJson(relativePath: string, value: unknown): Promise<void> {
  const outputPath = path.join(projectRoot, relativePath);
  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(outputPath, `${JSON.stringify(value, null, 2)}\n`);
}

async function main(): Promise<void> {
  const tznk = buildTznkSeeds().map((seed, index) => makeQuestion(seed, index + 1));
  const english = buildEnglishSeeds().map((seed, index) => makeQuestion(seed, index + 1));

  if (tznk.length !== 100) {
    throw new Error(`Expected 100 TZNK questions, got ${tznk.length}`);
  }

  if (english.length !== 120) {
    throw new Error(`Expected 120 English questions, got ${english.length}`);
  }

  const tznkDifficulty = distributionBy(tznk, (question) => question.difficulty);
  const expectedTznkDifficulty: Record<Difficulty, number> = { easy: 25, medium: 55, hard: 20 };

  for (const difficulty of ["easy", "medium", "hard"] as const) {
    if ((tznkDifficulty[difficulty] ?? 0) !== expectedTznkDifficulty[difficulty]) {
      throw new Error(`Unexpected TZNK ${difficulty} count: ${tznkDifficulty[difficulty] ?? 0}`);
    }
  }

  const englishTopic = distributionBy(english, (question) => question.topic);
  const expectedEnglishTopic: Record<string, number> = {
    "Reading comprehension": 54,
    Grammar: 30,
    Vocabulary: 24,
    "Cloze and sentence completion": 12
  };

  for (const [topic, expected] of Object.entries(expectedEnglishTopic)) {
    if ((englishTopic[topic] ?? 0) !== expected) {
      throw new Error(`Unexpected English ${topic} count: ${englishTopic[topic] ?? 0}`);
    }
  }

  assertUniqueSingleAnswer([...tznk, ...english]);

  await writeJson("data/generated/tznk.generated.json", tznk);
  await writeJson("data/generated/english.generated.json", english);

  const report = `# Generated Batch 1 Report

Generated on ${new Date().toISOString()}.

## Summary

- Generated ТЗНК questions: ${tznk.length}
- Generated English questions: ${english.length}
- Destination files: \`data/generated/tznk.generated.json\`, \`data/generated/english.generated.json\`
- Merged into public question bank: no
- Validation status: pending \`npm run validate:questions\`
- Questions marked for manual review: 0

${markdownDistribution("ТЗНК Distribution By Topic", distributionBy(tznk, (question) => question.topic))}

${markdownDistribution("ТЗНК Distribution By Difficulty", distributionBy(tznk, (question) => question.difficulty))}

${markdownDistribution("English Distribution By Topic", englishTopic)}

${markdownDistribution("English Distribution By Difficulty", distributionBy(english, (question) => question.difficulty))}

## Known Limitations

- The generated questions are original training material, not official exam questions.
- ТЗНК table/data items use plain-text table descriptions because the current schema does not include image/table attachments.
- English passage groups duplicate the passage in each related question, matching the current app schema.
- All generated questions have \`reviewed=false\` because they still need human editorial review before being treated as finalized content.
`;

  await fs.writeFile(path.join(projectRoot, "data/generated/generated-batch-1-report.md"), report);
  console.log(`Generated ${tznk.length} TZNK and ${english.length} English questions.`);
}

